-- Słowniki: odczyt dla wszystkich, zapis organizator, bez usuwania (AC-11, AC-47).
create policy "disciplines: read" on public.disciplines for select to anon, authenticated using (true);
create policy "disciplines: organizer insert" on public.disciplines for insert to authenticated
  with check ((select public.is_organizer()));
create policy "disciplines: organizer update" on public.disciplines for update to authenticated
  using ((select public.is_organizer())) with check ((select public.is_organizer()));
revoke delete on public.disciplines from anon, authenticated;

create policy "event_categories: read" on public.event_categories for select to anon, authenticated using (true);
create policy "event_categories: organizer insert" on public.event_categories for insert to authenticated
  with check ((select public.is_organizer()));
create policy "event_categories: organizer update" on public.event_categories for update to authenticated
  using ((select public.is_organizer())) with check ((select public.is_organizer()));
revoke delete on public.event_categories from anon, authenticated;

-- Regulaminy: publicznie tylko używane w opublikowanych zawodach.
create policy "rulebooks: read" on public.rulebooks for select to anon, authenticated
  using (
    (select public.is_organizer())
    or exists (select 1 from public.competitions c where c.rulebook_id = rulebooks.id and c.status = 'published')
  );
create policy "rulebooks: organizer write" on public.rulebooks for all to authenticated
  using ((select public.is_organizer())) with check ((select public.is_organizer()));

-- Zawody: publicznie tylko opublikowane; usuwanie tylko szkiców (AC-23).
create policy "competitions: read" on public.competitions for select to anon, authenticated
  using (status = 'published' or (select public.is_organizer()));
create policy "competitions: organizer insert" on public.competitions for insert to authenticated
  with check ((select public.is_organizer()));
create policy "competitions: organizer update" on public.competitions for update to authenticated
  using ((select public.is_organizer())) with check ((select public.is_organizer()));
create policy "competitions: organizer delete drafts" on public.competitions for delete to authenticated
  using ((select public.is_organizer()) and status = 'draft');

create policy "schedule_items: read" on public.schedule_items for select to anon, authenticated
  using (
    (select public.is_organizer())
    or exists (select 1 from public.competitions c where c.id = competition_id and c.status = 'published')
  );
create policy "schedule_items: organizer write" on public.schedule_items for all to authenticated
  using ((select public.is_organizer())) with check ((select public.is_organizer()));

create policy "calendar_events: read" on public.calendar_events for select to anon, authenticated
  using (status = 'published' or (select public.is_organizer()));
create policy "calendar_events: organizer write" on public.calendar_events for all to authenticated
  using ((select public.is_organizer())) with check ((select public.is_organizer()));

