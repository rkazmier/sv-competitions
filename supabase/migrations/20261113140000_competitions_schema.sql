-- Odczyt plików przez publiczny URL; przez API (lista, zapis, usuwanie) — tylko organizator.
create policy "documents: organizer read" on storage.objects for select to authenticated
  using (bucket_id = 'documents' and (select public.is_organizer()));
create policy "documents: organizer insert" on storage.objects for insert to authenticated
  with check (
    bucket_id = 'documents' and (select public.is_organizer())
    and (storage.foldername(name))[1] in ('rulebooks', 'matchbooks')
  );
create policy "documents: organizer update" on storage.objects for update to authenticated
  using (bucket_id = 'documents' and (select public.is_organizer()))
  with check (
    bucket_id = 'documents' and (select public.is_organizer())
    and (storage.foldername(name))[1] in ('rulebooks', 'matchbooks')
  );
create policy "documents: organizer delete" on storage.objects for delete to authenticated
  using (bucket_id = 'documents' and (select public.is_organizer()));
