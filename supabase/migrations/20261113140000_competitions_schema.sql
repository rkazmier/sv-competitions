-- ===== Tabele =====

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  role text not null default 'competitor' check (role in ('competitor', 'organizer')),
  created_at timestamptz not null default now()
);

create table public.disciplines (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(trim(name)) between 1 and 80),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);
create unique index disciplines_name_key on public.disciplines (lower(trim(name)));

create table public.event_categories (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(trim(name)) between 1 and 80),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);
create unique index event_categories_name_key on public.event_categories (lower(trim(name)));

create table public.rulebooks (
  id uuid primary key default gen_random_uuid(),
  title text not null check (length(trim(title)) between 1 and 200),
  file_path text not null unique,
  file_size integer not null check (file_size between 1 and 20971520),
  is_archived boolean not null default false,
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now()
);

create table public.competitions (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  name text not null check (length(trim(name)) between 1 and 150),
  discipline_id uuid not null references public.disciplines (id) on delete restrict,
  starts_on date not null,
  ends_on date check (ends_on is null or ends_on >= starts_on),
  description text check (length(description) <= 10000),
  rulebook_id uuid references public.rulebooks (id) on delete restrict,
  matchbook_path text,
  status text not null default 'draft' check (status in ('draft', 'published')),
  published_at timestamptz,
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint competitions_published_needs_rulebook check (status = 'draft' or rulebook_id is not null)
);

create table public.schedule_items (
  id uuid primary key default gen_random_uuid(),
  competition_id uuid not null references public.competitions (id) on delete cascade,
  day date not null,
  "time" time,
  description text not null check (length(trim(description)) between 1 and 300),
  position integer generated by default as identity
);
create index schedule_items_competition_idx on public.schedule_items (competition_id, day, "time", position);

create table public.calendar_events (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(trim(name)) between 1 and 150),
  category_id uuid not null references public.event_categories (id) on delete restrict,
  starts_on date not null,
  ends_on date check (ends_on is null or ends_on >= starts_on),
  description text check (length(description) <= 2000),
  external_url text check (external_url ~ '^https?://' and length(external_url) <= 2000),
  status text not null default 'draft' check (status in ('draft', 'published')),
  published_at timestamptz,
  created_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint calendar_events_published_needs_url check (status = 'draft' or external_url is not null)
);

-- ===== Funkcje =====

create function public.is_organizer()
returns boolean
language sql stable security definer set search_path = ''
as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'organizer');
$$;
revoke execute on function public.is_organizer() from public;
grant execute on function public.is_organizer() to anon, authenticated;

-- Profil z rolą `competitor` po utworzeniu konta (AC-7).
create function public.handle_new_user()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id) values (new.id);
  return new;
end;
$$;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- Custom Access Token Hook: claim `app_role` tylko dla UI; RLS używa is_organizer().
create function public.custom_access_token_hook(event jsonb)
returns jsonb
language plpgsql stable set search_path = ''
as $$
declare
  user_role text;
begin
  select role into user_role from public.profiles where id = (event ->> 'user_id')::uuid;
  return jsonb_set(event, '{claims,app_role}', to_jsonb(coalesce(user_role, 'competitor')));
end;
$$;
revoke execute on function public.custom_access_token_hook(jsonb) from public, anon, authenticated;
grant execute on function public.custom_access_token_hook(jsonb) to supabase_auth_admin;
grant usage on schema public to supabase_auth_admin;
grant select on table public.profiles to supabase_auth_admin;

-- created_by = zalogowany użytkownik, niezmienne; published_at przy pierwszej publikacji, potem niezmienne.
create function public.set_audit_fields()
returns trigger
language plpgsql set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    new.created_by := auth.uid();
    if tg_table_name <> 'rulebooks' then
      new.published_at := case when new.status = 'published' then now() end;
    end if;
  else
    new.created_by := old.created_by;
    new.created_at := old.created_at;
    if tg_table_name <> 'rulebooks' then
      new.published_at := coalesce(old.published_at, case when new.status = 'published' then now() end);
      new.updated_at := now();
    end if;
  end if;
  return new;
end;
$$;

-- Plik regulaminu jest niezmienny (AC-16), można poprawić tytuł.
create function public.rulebooks_file_immutable()
returns trigger
language plpgsql set search_path = ''
as $$
begin
  if new.file_path <> old.file_path or new.file_size <> old.file_size then
    raise exception 'rulebook_file_immutable' using errcode = 'check_violation';
  end if;
  return new;
end;
$$;

-- slug: `<starts_on>-<nazwa-ascii>`, sufiks -2, -3… przy kolizji; zamrożony od pierwszej publikacji (AC-28).
create function public.slugify(value text)
returns text
language sql stable set search_path = ''
as $$
  select trim(both '-' from regexp_replace(lower(extensions.unaccent('extensions.unaccent'::regdictionary, value)), '[^a-z0-9]+', '-', 'g'));
$$;

create function public.set_competition_slug()
returns trigger
language plpgsql set search_path = ''
as $$
declare
  base text;
  candidate text;
  n integer := 1;
begin
  if tg_op = 'UPDATE' and old.published_at is not null then
    new.slug := old.slug;
    return new;
  end if;
  base := trim(both '-' from new.starts_on::text || '-' || left(public.slugify(new.name), 80));
  candidate := base;
  while exists (select 1 from public.competitions where slug = candidate and id <> new.id) loop
    n := n + 1;
    candidate := base || '-' || n;
  end loop;
  new.slug := candidate;
  return new;
end;
$$;

-- Dzień punktu harmonogramu w terminie zawodów (AC-22), także przy zmianie dat zawodów.
create function public.check_schedule_item_day()
returns trigger
language plpgsql set search_path = ''
as $$
begin
  if not exists (
    select 1 from public.competitions c
    where c.id = new.competition_id and new.day between c.starts_on and coalesce(c.ends_on, c.starts_on)
  ) then
    raise exception 'schedule_item_day_out_of_range' using errcode = 'check_violation';
  end if;
  return new;
end;
$$;

create function public.check_competition_schedule_range()
returns trigger
language plpgsql set search_path = ''
as $$
begin
  if exists (
    select 1 from public.schedule_items s
    where s.competition_id = new.id and s.day not between new.starts_on and coalesce(new.ends_on, new.starts_on)
  ) then
    raise exception 'schedule_item_day_out_of_range' using errcode = 'check_violation';
  end if;
  return new;
end;
$$;

